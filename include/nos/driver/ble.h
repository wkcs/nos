#ifndef NOS_DRIVER_BLE_H
#define NOS_DRIVER_BLE_H
#include "device.h"
#define NOS_BLE_SERVICES 4u
#define NOS_BLE_ATTRIBUTES 16u
#define NOS_BLE_VALUE_MAX 244u
#define NOS_BLE_CONNECTIONS 4u
#define NOS_BLE_EVENTS 8u
#define NOS_BLE_READ 1u
#define NOS_BLE_WRITE 2u
#define NOS_BLE_WRITE_NO_RESPONSE 4u
#define NOS_BLE_NOTIFY 8u
#define NOS_BLE_INDICATE 16u
#define NOS_BLE_ENCRYPTED 32u
#define NOS_BLE_AUTHENTICATED 64u
/* Bluetooth little-endian UUID bytes; size is 2 or 16. */
struct nos_ble_uuid {
    uint8_t size, value[16];
};
struct nos_ble_attribute {
    struct nos_ble_uuid uuid;
    uint16_t id, parent, flags, max_length, initial_length;
    uint8_t service;
    const void *initial_value;
};
/* parent=0 declares a characteristic; otherwise a descriptor of that id.
 * CCCD is generated by the host for NOTIFY/INDICATE, never declare 0x2902.
 * Profile, strings and descriptor arrays remain immutable until shutdown. */
struct nos_ble_profile {
    const char *name;
    const struct nos_ble_uuid *services;
    const struct nos_ble_attribute *attributes;
    uint8_t service_count, attribute_count;
    /* Bluetooth IO capability 0..4 (display, display/yes-no, keyboard,
     * no-input/output, keyboard/display). NULL selects no-input/output + SC. */
    const struct nos_ble_security *security;
};
struct nos_ble_security {
    uint8_t io_capability, bonding, mitm, secure_connections;
};
enum nos_ble_pairing_action { NOS_BLE_PAIR_INPUT = 1, NOS_BLE_PAIR_DISPLAY, NOS_BLE_PAIR_COMPARE };
struct nos_ble_pairing {
    uint32_t passkey;
    uint16_t connection;
    uint8_t action, accept;
};
enum nos_ble_event_type {
    NOS_BLE_READY = 1,
    NOS_BLE_CONNECTED,
    NOS_BLE_DISCONNECTED,
    NOS_BLE_WRITTEN,
    NOS_BLE_SUBSCRIBED,
    NOS_BLE_MTU,
    NOS_BLE_TX_COMPLETE,
    NOS_BLE_ADV_COMPLETE,
    NOS_BLE_RESET,
    NOS_BLE_PAIRING,
    NOS_BLE_ENCRYPTION
};
struct nos_ble_event {
    uint32_t dropped;
    int32_t status; /* zero or negative NOS driver error, never an SDK enum */
    uint16_t connection, attribute, length;
    uint8_t type;
    uint8_t value[NOS_BLE_VALUE_MAX];
};
struct nos_ble_value {
    void *data;
    size_t size, actual;
    uint16_t connection, attribute;
    uint8_t indicate;
};
struct nos_ble_advertise {
    uint16_t min_ms, max_ms;
    uint8_t connectable;
};
struct nos_ble_status {
    uint32_t dropped;
    uint8_t synced, advertising, connections;
};
/* Caller serializes all state operations; the SDK adapter supplies a short
 * callback-safe critical section. No SDK calls while holding that section. */
struct nos_ble_gatt {
    const struct nos_ble_profile *profile;
    uint8_t values[NOS_BLE_ATTRIBUTES][NOS_BLE_VALUE_MAX];
    uint16_t lengths[NOS_BLE_ATTRIBUTES];
    struct {
        uint16_t handle, mtu, notify, indicate;
        uint8_t used;
    } peers[NOS_BLE_CONNECTIONS];
    struct nos_ble_event events[NOS_BLE_EVENTS];
    uint32_t dropped;
    uint8_t head, count;
};
int nos_ble_gatt_init(struct nos_ble_gatt *, const struct nos_ble_profile *);
int nos_ble_gatt_find(const struct nos_ble_gatt *, uint16_t id);
int nos_ble_gatt_get(struct nos_ble_gatt *, uint16_t, void *, size_t, size_t *, int remote);
int nos_ble_gatt_set(struct nos_ble_gatt *, uint16_t, const void *, size_t, uint16_t conn,
                     int remote);
int nos_ble_gatt_peer(struct nos_ble_gatt *, uint16_t conn, int connected);
int nos_ble_gatt_mtu(struct nos_ble_gatt *, uint16_t conn, uint16_t mtu);
int nos_ble_gatt_subscribe(struct nos_ble_gatt *, uint16_t conn, uint16_t id, int notify,
                           int indicate);
int nos_ble_gatt_can_notify(struct nos_ble_gatt *, uint16_t conn, uint16_t id, size_t,
                            int indicate);
int nos_ble_gatt_emit(struct nos_ble_gatt *, const struct nos_ble_event *);
int nos_ble_gatt_event(struct nos_ble_gatt *, struct nos_ble_event *);
int nos_ble_advertising_data(const struct nos_ble_profile *, uint8_t out[31], size_t *length);
#endif

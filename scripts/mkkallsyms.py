#!/usr/bin/env python3
import argparse
from collections import Counter
import subprocess
import sys


def parse_symbols_from_lines(lines):
    symbols = []
    seen_addrs = set()
    for line in lines:
        parts = line.strip().split()
        if len(parts) < 3:
            continue
        addr_str = parts[0]
        if len(parts) == 3 and parts[1].upper() in ["T", "t"]:
            try:
                addr = int(addr_str, 16)
                name = parts[2].split(".", 1)[0]
                if addr != 0 and name and not name.startswith("$") and addr not in seen_addrs:
                    seen_addrs.add(addr)
                    symbols.append((addr, name))
            except ValueError:
                continue
            continue
        if ".text" in parts and len(parts) >= 4:
            sec_idx = parts.index(".text")
            flags = parts[1:sec_idx]
            if "d" in flags or "O" in flags or "df" in flags:
                continue
            name = parts[-1]
            if name == ".text" or name.startswith("$") or name.startswith("."):
                continue
            name = name.split(".", 1)[0]
            if not name:
                continue
            try:
                addr = int(addr_str, 16)
                if addr != 0 and addr not in seen_addrs:
                    seen_addrs.add(addr)
                    symbols.append((addr, name))
            except ValueError:
                continue
    symbols.sort(key=lambda x: x[0])
    return symbols


def compress_symbol_names(symbols):
    seqs = [list(name.encode("ascii", errors="ignore")) for _, name in symbols]
    tokens = []
    for tok_id in range(128, 256):
        pairs = Counter()
        for seq in seqs:
            for i in range(len(seq) - 1):
                pairs[(seq[i], seq[i + 1])] += 1
        if not pairs:
            break
        best_pair, count = pairs.most_common(1)[0]
        if count < 2:
            break
        tokens.append(best_pair)
        a, b = best_pair
        for seq in seqs:
            i = 0
            while i < len(seq) - 1:
                if seq[i] == a and seq[i + 1] == b:
                    seq[i : i + 2] = [tok_id]
                else:
                    i += 1

    flat_bytes = []
    offsets = []
    for seq in seqs:
        offsets.append(len(flat_bytes))
        flat_bytes.extend(seq)
        flat_bytes.append(0)
    if not flat_bytes:
        flat_bytes.append(0)
    return tokens, flat_bytes, offsets


def write_kallsyms_c(symbols, output_file):
    tokens, flat_bytes, offsets = compress_symbol_names(symbols)
    token_bytes = [0] * 256
    for idx, (a, b) in enumerate(tokens):
        token_bytes[idx * 2] = a
        token_bytes[idx * 2 + 1] = b

    with open(output_file, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by scripts/mkkallsyms.py */\n")
        f.write("#include <kernel/kallsyms.h>\n\n")
        f.write("const unsigned char kallsyms_token_table[256] = {\n")
        for row in range(0, 256, 16):
            chunk = ", ".join(f"0x{b:02x}" for b in token_bytes[row : row + 16])
            f.write(f"    {chunk},\n")
        f.write("};\n\n")
        f.write("static const unsigned char kallsyms_names[] = {\n")
        for row in range(0, len(flat_bytes), 16):
            chunk = ", ".join(f"0x{b:02x}" for b in flat_bytes[row : row + 16])
            f.write(f"    {chunk},\n")
        f.write("};\n\n")
        f.write("const struct kallsym_entry kallsyms_table[] = {\n")
        for (addr, _), off in zip(symbols, offsets):
            f.write(f"    {{ 0x{addr:08x}, (const char *)&kallsyms_names[{off}] }},\n")
        f.write("    { 0, (const char *)0 }\n")
        f.write("};\n\n")
        f.write(f"const unsigned int kallsyms_num = {len(symbols)};\n")


def generate_kallsyms(map_file, output_file):
    with open(map_file, "r", encoding="utf-8", errors="replace") as f:
        symbols = parse_symbols_from_lines(f)
    write_kallsyms_c(symbols, output_file)


def main():
    # Backward-compatible positional mode: mkkallsyms.py <nm_output> <output_c_file>
    if len(sys.argv) == 3 and not sys.argv[1].startswith("-"):
        generate_kallsyms(sys.argv[1], sys.argv[2])
        return 0

    parser = argparse.ArgumentParser(description="Cross-platform NOS kallsyms generator")
    parser.add_argument("--empty", help="Write an empty pass-1 kallsyms C file to this path")
    parser.add_argument("--objdump", help="Path to objdump executable")
    parser.add_argument("--elf", help="Path to pass-1 ELF binary")
    parser.add_argument("--out", help="Output C file path")
    parser.add_argument("--disasm", help="Write objdump -S disassembly listing to this path")
    args = parser.parse_args()

    if args.empty:
        write_kallsyms_c([], args.empty)
        return 0

    if args.objdump and args.elf and args.disasm:
        with open(args.disasm, "w", encoding="utf-8", errors="replace") as out_f:
            subprocess.run(
                [args.objdump, "-S", args.elf],
                stdout=out_f,
                stderr=subprocess.PIPE,
                check=True,
            )
        return 0

    if args.objdump and args.elf and args.out:
        res = subprocess.run(
            [args.objdump, "-t", args.elf],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            encoding="utf-8",
            errors="replace",
            check=True,
        )
        symbols = parse_symbols_from_lines(res.stdout.splitlines())
        write_kallsyms_c(symbols, args.out)
        return 0

    parser.print_help()
    return 1


if __name__ == "__main__":
    sys.exit(main())

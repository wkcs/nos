import argparse
import datetime
import os
import re
import sys

# Ensure bundled scripts/kconfiglib.py is importable
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
if SCRIPT_DIR not in sys.path:
    sys.path.insert(0, SCRIPT_DIR)

import kconfiglib  # noqa: E402


LEGACY_BOARD_MAP = {
    "nk60-v2": ("BOARD_NK60", "ARM_CORTEX_M4", "SOC_STM32F4"),
    "nk60": ("BOARD_NK60", "ARM_CORTEX_M4", "SOC_STM32F4"),
    "qemu-stm32": ("BOARD_QEMU_STM32", "ARM_CORTEX_M3", "SOC_STM32F1"),
    "wl-001": ("BOARD_WL_001", "ARM_CORTEX_M3", "SOC_STM32F1"),
    "zj-v3": ("BOARD_ZJ_V3", "ARM_CORTEX_M3", "SOC_STM32F1"),
    "qemu-virt": ("BOARD_QEMU_VIRT", None, "SOC_QEMU_VIRT"),
}

LEGACY_CPU_MAP = {
    "cortex-m3": "ARM_CORTEX_M3",
    "cortex-m4": "ARM_CORTEX_M4",
    "cortex-a7": "ARM_CORTEX_A7",
    "cortex-a53": "ARM64_CORTEX_A53",
    "cortex-a72": "ARM64_CORTEX_A72",
}


def normalize_legacy_config_lines(path):
    """
    Support both standard Kconfig defconfigs and legacy arch/arm/config/*_config
    files where string symbols like CONFIG_BOARD="wl-001" or bare SYM=y were used.
    """
    normalized = []
    board_val = None
    cpu_val = None
    with open(path, "r", encoding="utf-8") as f:
        for raw in f:
            line = raw.strip()
            if not line or line.startswith("#"):
                normalized.append(raw)
                continue
            if not line.startswith("CONFIG_") and "=" in line:
                line = "CONFIG_" + line
            m_board = re.match(r'^CONFIG_BOARD="([^"]+)"$', line)
            if m_board:
                board_val = m_board.group(1)
                continue
            m_cpu = re.match(r'^CONFIG_CPU_TYPE="([^"]+)"$', line)
            if m_cpu:
                cpu_val = m_cpu.group(1)
                continue
            normalized.append(line + "\n")

    header_inject = []
    if cpu_val and cpu_val in LEGACY_CPU_MAP:
        header_inject.append(f"CONFIG_{LEGACY_CPU_MAP[cpu_val]}=y\n")
    if board_val and board_val in LEGACY_BOARD_MAP:
        b_sym, c_sym, s_sym = LEGACY_BOARD_MAP[board_val]
        header_inject.append(f"CONFIG_{b_sym}=y\n")
        if c_sym and not cpu_val:
            header_inject.append(f"CONFIG_{c_sym}=y\n")

    return "".join(header_inject + normalized)


def cmake_escape(val):
    return val.replace("\\", "\\\\").replace('"', '\\"')


def write_kconfig_cmake(kconf, cmake_path):
    lines = [
        "# Automatically generated by scripts/gen_kconfig_cmake.py — DO NOT EDIT\n"
    ]
    for sym in kconf.unique_defined_syms:
        if sym.type in (kconfiglib.BOOL, kconfiglib.TRISTATE):
            if sym.str_value == "y":
                lines.append(f'set(CONFIG_{sym.name} "y")\n')
            elif sym.str_value == "m":
                lines.append(f'set(CONFIG_{sym.name} "m")\n')
            else:
                lines.append(f"unset(CONFIG_{sym.name})\n")
        elif sym.type in (kconfiglib.INT, kconfiglib.HEX):
            if sym.str_value:
                lines.append(f'set(CONFIG_{sym.name} "{sym.str_value}")\n')
        elif sym.type == kconfiglib.STRING:
            escaped = cmake_escape(sym.str_value)
            lines.append(f'set(CONFIG_{sym.name} "{escaped}")\n')
    with open(cmake_path, "w", encoding="utf-8") as f:
        f.writelines(lines)


def main():
    parser = argparse.ArgumentParser(
        description="Generate .config, autocfg.h, autoconf.h, and kconfig.cmake from Kconfig"
    )
    parser.add_argument(
        "--srctree",
        default=".",
        help="Root directory of NOS source tree (containing top-level Kconfig)",
    )
    parser.add_argument(
        "--kconfig",
        default="Kconfig",
        help="Top-level Kconfig filename relative to srctree",
    )
    parser.add_argument(
        "--out-dir",
        required=True,
        help="Output directory for .config, include/autocfg.h, and kconfig.cmake",
    )
    parser.add_argument(
        "--version",
        default="1.0.0",
        help="Kernel version string MAJOR.MINOR.PATCH",
    )
    parser.add_argument(
        "configs",
        nargs="+",
        help="Base defconfig followed by optional config fragments",
    )
    args = parser.parse_args()

    srctree = os.path.abspath(args.srctree)
    out_dir = os.path.abspath(args.out_dir)
    inc_dir = os.path.join(out_dir, "include")
    gen_dir = os.path.join(out_dir, "include", "generated")
    os.makedirs(inc_dir, exist_ok=True)
    os.makedirs(gen_dir, exist_ok=True)

    os.environ["srctree"] = srctree
    old_cwd = os.getcwd()
    try:
        os.chdir(srctree)
        kconf = kconfiglib.Kconfig(args.kconfig, warn_to_stderr=False)

        for idx, cfg_path in enumerate(args.configs):
            abs_cfg = (
                cfg_path
                if os.path.isabs(cfg_path)
                else os.path.join(old_cwd, cfg_path)
            )
            if not os.path.isfile(abs_cfg):
                abs_cfg = os.path.join(srctree, cfg_path)
            if not os.path.isfile(abs_cfg):
                sys.stderr.write(f"Error: config file not found: {cfg_path}\n")
                return 1

            norm_content = normalize_legacy_config_lines(abs_cfg)
            tmp_cfg = os.path.join(out_dir, f".tmp_fragment_{idx}.config")
            with open(tmp_cfg, "w", encoding="utf-8") as tf:
                tf.write(norm_content)
            kconf.load_config(tmp_cfg, replace=(idx == 0))
            os.remove(tmp_cfg)

        # Populate VERSION_CODE and BUILD_INFO
        parts = [int(x) for x in (args.version.split(".") + ["0", "0"])[:3]]
        ver_code = (parts[0] << 16) | (parts[1] << 8) | parts[2]
        if "VERSION_CODE" in kconf.syms:
            kconf.syms["VERSION_CODE"].set_value(str(ver_code))
        if "BUILD_INFO" in kconf.syms and not kconf.syms["BUILD_INFO"].str_value:
            now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
            kconf.syms["BUILD_INFO"].set_value(now_str)

        dot_config = os.path.join(out_dir, ".config")
        autocfg_h = os.path.join(inc_dir, "autocfg.h")
        autoconf_h = os.path.join(inc_dir, "autoconf.h")
        gen_autoconf_h = os.path.join(gen_dir, "autoconf.h")
        kconfig_cmake = os.path.join(out_dir, "kconfig.cmake")

        kconf.write_config(dot_config)
        kconf.write_autoconf(
            autocfg_h,
            header=(
                "/*\n"
                " * Automatically generated C config: don't edit\n"
                " * NOS Kernel Configuration\n"
                " */\n"
                "#ifndef __NOS_AUTOCFG_H__\n"
                "#define __NOS_AUTOCFG_H__\n\n"
            ),
        )
        with open(autocfg_h, "a", encoding="utf-8") as f:
            f.write("\n#endif /* __NOS_AUTOCFG_H__ */\n")

        # Keep autoconf.h in sync for tools/scripts expecting Linux naming
        with open(autocfg_h, "r", encoding="utf-8") as src:
            hdr_text = src.read()
        for target_h in (autoconf_h, gen_autoconf_h):
            with open(target_h, "w", encoding="utf-8") as dst:
                dst.write(hdr_text)

        write_kconfig_cmake(kconf, kconfig_cmake)
    finally:
        os.chdir(old_cwd)

    arch_val = kconf.syms["ARCH"].str_value if "ARCH" in kconf.syms else "unknown"
    board_val = kconf.syms["BOARD"].str_value if "BOARD" in kconf.syms else "unknown"
    cpu_val = kconf.syms["CPU_TYPE"].str_value if "CPU_TYPE" in kconf.syms else "unknown"
    print(
        f"-- [Kconfig] ARCH={arch_val} CPU={cpu_val} BOARD={board_val} -> {dot_config}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())

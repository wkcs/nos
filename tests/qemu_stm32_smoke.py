        proc.stdin.flush()
        wait_for(b"nohome\r\n", pos)
        wait_for(b"missing\r\n/\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"cd -L -z || echo bad-option; pwd --\r")
        proc.stdin.flush()

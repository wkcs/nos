#!/usr/bin/env python3
"""Exercise boot, the IRQ-backed shell, and log statistics in QEMU."""

from pathlib import Path
import argparse
import os
import selectors
import signal
import subprocess
import time


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("elf", type=Path)
    parser.add_argument("--log", type=Path)
    args = parser.parse_args()

    elf = args.elf.resolve()
    command = ["qemu-system-arm", "-M", "netduinoplus2", "-nographic",
               "-semihosting", "-semihosting-config", "enable=on,target=native",
               "-kernel", str(elf)]
    proc = subprocess.Popen(command, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, start_new_session=True, cwd=elf.parent)
    selector = selectors.DefaultSelector()
    selector.register(proc.stdout, selectors.EVENT_READ)
    output = bytearray()

    def wait_for(needle, start=0, timeout=10):
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if needle in output[start:]:
                return
            for key, _ in selector.select(0.1):
                data = os.read(key.fd, 8192)
                if data:
                    output.extend(data)
                elif proc.poll() is not None:
                    raise RuntimeError(f"QEMU exited with {proc.returncode}")
        raise RuntimeError(f"timed out waiting for {needle!r}")

    def wait_count(needle, count, start=0, timeout=10):
        deadline = time.monotonic() + timeout
        while output[start:].count(needle) < count:
            if time.monotonic() >= deadline:
                raise RuntimeError(f"timed out waiting for {count} occurrences of {needle!r}")
            for key, _ in selector.select(0.1):
                data = os.read(key.fd, 8192)
                if data:
                    output.extend(data)
                elif proc.poll() is not None:
                    raise RuntimeError(f"QEMU exited with {proc.returncode}")

    try:
        wait_for(b"Welcome to NOS:")
        wait_for(b"vfs_smoke OK")
        wait_for(b"nos# ")
        pos = len(output)
        proc.stdin.write(b"help\r")
        proc.stdin.flush()
        wait_for(b"Available commands:", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"echo 'hello world'\r")
        proc.stdin.flush()
        wait_for(b"\r\nhello world\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"echo bad |\r")
        proc.stdin.flush()
        wait_for(b"shell: syntax error", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"echo 'pipe data' | cat | cat\r")
        proc.stdin.flush()
        wait_for(b"\r\npipe data\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"echo 'one two' | wc -w\r")
        proc.stdin.flush()
        wait_for(b"\r\n2\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"echo 'Hello World' | grep -i world | wc -l\r")
        proc.stdin.flush()
        wait_for(b"\r\n1\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"false && echo skipped; echo $?; false; echo value > /tmp/s$?; cat /tmp/s1\r")
        proc.stdin.flush()
        wait_for(b"\r\n1\r\n", pos)
        wait_for(b"value\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"false && echo skip | cat || echo pipe-skipped\r")
        proc.stdin.flush()
        wait_for(b"\r\npipe-skipped\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"cat /missing | cat\r")
        proc.stdin.flush()
        wait_for(b"cat: /missing: not found\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"ls /missing > /tmp/error-output\r")
        proc.stdin.flush()
        wait_for(b"ls: cannot access '/missing'\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"cat /tmp/error-output; echo stderr-check\r")
        proc.stdin.flush()
        wait_for(b"\r\nstderr-check\r\n", pos)
        wait_for(b"nos# ", pos)
        if b"ls: cannot access" in output[pos:]:
            raise RuntimeError("stderr was written to the redirected stdout file")
        pos = len(output)
        proc.stdin.write(b"false && echo no || echo yes; true && echo done\r")
        proc.stdin.flush()
        wait_for(b"\r\nyes\r\ndone\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"false; echo status=$? \"$?\" '$?' \\$?; true; echo ${?}\r")
        proc.stdin.flush()
        wait_for(b"\r\nstatus=1 1 $? $?\r\n0\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"false; true | echo $?\r")
        proc.stdin.flush()
        wait_for(b"\r\n1\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"NAME='one two'; echo \"$NAME\"; echo ${NAME}\r")
        proc.stdin.flush()
        wait_for(b"\r\none two\r\none two\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"NAME='a;echo injected'; echo \"$NAME\"; unset NAME; echo x${NAME}y\r")
        proc.stdin.flush()
        wait_for(b"\r\na;echo injected\r\nxy\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"NAME='one two'; export COPY=$NAME; echo \"$COPY\"; unset -v NAME COPY; echo x${COPY}y\r")
        proc.stdin.flush()
        wait_for(b"\r\none two\r\nxy\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"'NOT_ASSIGN=1'; echo $?; echo x${NOT_ASSIGN}y\r")
        proc.stdin.flush()
        wait_for(b"NOT_ASSIGN=1: command not found", pos)
        wait_for(b"\r\n127\r\nxy\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"history\r")
        proc.stdin.flush()
        wait_for(b"'NOT_ASSIGN=1'; echo $?; echo x${NOT_ASSIGN}y\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"history -c\r")
        proc.stdin.flush()
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"mkdir /tmp/one /tmp/two\r")
        proc.stdin.flush()
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"mkdir -p /tmp/nested/child; mkdir -p /tmp/nested/child\r")
        proc.stdin.flush()
        wait_for(b"nos# ", pos)
        if b"mkdir: cannot create" in output[pos:]:
            raise RuntimeError("mkdir -p did not create or reuse parent directories")
        pos = len(output)
        proc.stdin.write(b"cd /tmp/nested/child; pwd\r")
        proc.stdin.flush()
        wait_for(b"\r\n/tmp/nested/child\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"cd /tmp/two\r")
        proc.stdin.flush()
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"pwd\r")
        proc.stdin.flush()
        wait_for(b"\r\n/tmp/two\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"pwd > cwd; cat cwd\r")
        proc.stdin.flush()
        wait_for(b"\r\n/tmp/two\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"echo streamed | cat > piped; cat piped\r")
        proc.stdin.flush()
        wait_for(b"\r\nstreamed\n", pos)
        wait_for(b"nos# ", pos)
        for _ in range(22):
            pos = len(output)
            proc.stdin.write(b"echo " + b"x" * 200 + b" >> large\r")
            proc.stdin.flush()
            wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"cat large | cat || echo pipe-overflow\r")
        proc.stdin.flush()
        wait_for(b"shell: output error", pos)
        wait_for(b"pipe-overflow\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"echo hello > file; echo world >> file; cat file\r")
        proc.stdin.flush()
        wait_for(b"\r\nhello\nworld\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"mkdir -p file/sub || echo not-directory\r")
        proc.stdin.flush()
        wait_for(b"mkdir: cannot create", pos)
        wait_for(b"\r\nnot-directory\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"wc -c < file\r")
        proc.stdin.flush()
        wait_for(b"\r\n12\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"wc -lwc file file\r")
        proc.stdin.flush()
        wait_for(b"2 2 12 file\r\n", pos)
        wait_for(b"4 4 24 total\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"grep -n world file\r")
        proc.stdin.flush()
        wait_for(b"2:world\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"grep -vc world file\r")
        proc.stdin.flush()
        wait_for(b"\r\n1\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"echo -n 'Alpha*' > nonl; grep -Fi 'a*' nonl\r")
        proc.stdin.flush()
        wait_for(b"\r\nAlpha*\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"grep missing file || echo no-match\r")
        proc.stdin.flush()
        wait_for(b"\r\nno-match\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"cat < missing > file || echo failed; cat file\r")
        proc.stdin.flush()
        wait_for(b"cannot redirect", pos)
        wait_for(b"\r\nfailed\r\n", pos)
        wait_for(b"hello\nworld\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"cat < file\r")
        proc.stdin.flush()
        wait_for(b"\r\nhello\nworld\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"echo denied > /sys/arch || echo failed\r")
        proc.stdin.flush()
        wait_for(b"cannot redirect", pos)
        wait_for(b"\r\nfailed\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"cat /sys/arch /sys/board\r")
        proc.stdin.flush()
        wait_for(b"arm\nqemu-stm32\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"ls /sys/arch\r")
        proc.stdin.flush()
        wait_for(b"\r\n/sys/arch\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"log stats\r")
        proc.stdin.flush()
        wait_for(b"dropped=", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"log stats\r" * 5)
        proc.stdin.flush()
        wait_count(b"dropped=", 5, pos)
        wait_count(b"nos# ", 5, pos)
        print("QEMU STM32 boot, help, log statistics and RX burst passed")
    finally:
        if proc.poll() is None:
            os.killpg(proc.pid, signal.SIGTERM)
            proc.wait(timeout=3)
        selector.close()
        if args.log:
            args.log.write_bytes(output)


if __name__ == "__main__":
    main()

        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"[ -d /tmp ] && [ 4 -gt 3 ] && echo test-ok; test -f /tmp || echo not-file\r")
        proc.stdin.flush()
        wait_for(b"\r\ntest-ok\r\nnot-file\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"test ! ''; echo $?; test 4 -eq bad; echo $?; [ x = x; echo $?\r")
        proc.stdin.flush()
        wait_for(b"\r\n0\r\n", pos)
        wait_count(b"\r\n2\r\n", 2, pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"test -d /tmp -a 3 -gt 2 -o '' && echo combined\r")
        proc.stdin.flush()
        wait_for(b"\r\ncombined\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"test -n x -a -n x -a -n x -a -n x -a -n x && echo deep-test\r")
        proc.stdin.flush()
        wait_for(b"\r\ndeep-test\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"printf '%s:%03d\\n' one 7 two 8 | cat\r")
        proc.stdin.flush()
        wait_for(b"\r\none:007\ntwo:008\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"printf '%b' 'hello\\nworld\\cignored'; echo end\r")
        proc.stdin.flush()
        wait_for(b"\r\nhello\nworldend\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"> /tmp/empty; [ -f /tmp/empty ] && echo empty-created\r")
        proc.stdin.flush()
        wait_for(b"\r\nempty-created\r\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"NAME='file with space'; > /tmp/redir A='one two'; echo \"$A\" > /tmp/$NAME; cat \"/tmp/$NAME\"\r")
        proc.stdin.flush()
        wait_for(b"one two\n", pos)
        wait_for(b"nos# ", pos)
        pos = len(output)
        proc.stdin.write(b"echo data > /tmp/empty; > /tmp/empty; wc -c /tmp/empty\r")
